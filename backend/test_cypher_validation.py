class NodeTypeChecker:
    """Checks if Cypher is using the correct node types based on structural probe."""

    def __init__(self):
        self.neo4j_tools = Neo4jTools()

    def check_node_usage(self, cypher: str, expected_node: str, structural_probe: Dict) -> Dict[str, Any]:
        """
        Check if Cypher is using the expected node type.

        Args:
            cypher: Generated Cypher query
            expected_node: Expected node type (e.g., "Cell", "Line", "Cell|Line")
            structural_probe: Results from structural probe

        Returns:
            Dict with analysis results
        """
        result = {
            "expected_node": expected_node,
            "nodes_used": [],
            "is_correct": False,
            "issues": [],
            "recommendations": []
        }

        # Extract node types from Cypher
        node_pattern = r'\(\s*\w*\s*:\s*(\w+)'
        nodes_used = list(set(re.findall(node_pattern, cypher)))
        result["nodes_used"] = nodes_used

        # Check expected nodes
        expected_nodes = expected_node.split("|")

        # Determine which data nodes are used (Cell, Line, Section)
        data_nodes_used = [n for n in nodes_used if n in ['Cell', 'Line', 'Section', 'MergedCell']]

        if not data_nodes_used:
            result["issues"].append("No data nodes (Cell/Line/Section) found in query")
            return result

        # Check if any expected node is used
        for data_node in data_nodes_used:
            if data_node in expected_nodes or 'MergedCell' in expected_nodes and data_node == 'Cell':
                result["is_correct"] = True
                break

        if not result["is_correct"]:
            result["issues"].append(
                f"Expected {expected_node} but query uses {', '.join(data_nodes_used)}"
            )

        # Check against structural probe
        if structural_probe.get("found_in"):
            probe_has_cell = any(
                loc["node_type"] in ["Cell", "MergedCell"]
                for term_locs in structural_probe["found_in"].values()
                for loc in term_locs
            )
            probe_has_line = any(
                loc["node_type"] == "Line"
                for term_locs in structural_probe["found_in"].values()
                for loc in term_locs
            )

            # Check for mismatch between probe and query
            if "Cell" in data_nodes_used and not probe_has_cell and probe_has_line:
                result["issues"].append(
                    "PROBE MISMATCH: Structural probe found data in Line nodes, but query uses Cell"
                )
                result["recommendations"].append("Consider using Line nodes instead of Cell")

            if "Line" in data_nodes_used and not probe_has_line and probe_has_cell:
                result["issues"].append(
                    "PROBE MISMATCH: Structural probe found data in Cell nodes, but query uses Line"
                )
                result["recommendations"].append("Consider using Cell nodes instead of Line")

        return result

    def close(self):
        """Close Neo4j connection."""
        self.neo4j_tools.close()


