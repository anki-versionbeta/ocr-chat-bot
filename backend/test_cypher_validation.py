def test_hard_constraints(structural_probe: Dict, weaviate_chunks: List[Dict], user_query: str) -> Dict[str, Any]:
    """
    Test if hard constraints are being correctly extracted.

    Args:
        structural_probe: Results from structural probe
        weaviate_chunks: Weaviate chunks
        user_query: User query

    Returns:
        Dict with constraint analysis
    """
    constraints = extract_hard_constraints(structural_probe, weaviate_chunks, user_query)

    analysis = {
        "constraints": constraints,
        "primary_node": constraints.get("primary_node"),
        "forbidden_nodes": constraints.get("forbidden_nodes", []),
        "required_path": constraints.get("required_path"),
        "reasoning": constraints.get("reasoning", []),
        "issues": []
    }

    # Check if constraints are set
    if not constraints.get("primary_node"):
        analysis["issues"].append("No primary node constraint determined")

    # Check for conflicting constraints
    if constraints.get("primary_node") in constraints.get("forbidden_nodes", []):
        analysis["issues"].append("Primary node is in forbidden nodes list - CONFLICT!")

    return analysis


