# CYPHER SYNTAX VALIDATOR
# =============================================================================

class CypherSyntaxValidator:
    """Validates Cypher query syntax without executing."""

    # Valid node types in the schema
    VALID_NODE_TYPES = ['Document', 'Page', 'Table', 'Cell', 'MergedCell', 'Line', 'Section', 'Word', 'KV']

    # Valid relationships
    VALID_RELATIONSHIPS = [
        'HAS_PAGE', 'CONTAINS_TABLE', 'HAS_CELL', 'CONTAINS_LINE',
        'CONTAINS_SECTION', 'SAME_ROW', 'SAME_COL', 'HAS_WORD', 'HAS_KV'
    ]

    # Common Cypher syntax errors
    SYNTAX_ERROR_PATTERNS = [
        (r'MATCH\s+\(\s*\)', "Empty MATCH pattern"),
        (r'WHERE\s+AND', "WHERE followed by AND without condition"),
        (r'\)\s*-\s*\[\s*:\s*\]', "Empty relationship type"),
        (r'RETURN\s*$', "RETURN with no columns"),
        (r'ORDER BY\s*$', "ORDER BY with no columns"),
        (r'\s+AS\s*$', "AS with no alias"),
        (r'collect\(\s*\)', "Empty collect()"),
        (r'\$\s*\)', "Unterminated parameter"),
    ]

    def __init__(self):
        self.errors = []
        self.warnings = []

    def validate(self, cypher: str) -> Tuple[bool, List[str], List[str]]:
        """
        Validate Cypher syntax.

        Returns:
            Tuple of (is_valid, errors, warnings)
        """
        self.errors = []
        self.warnings = []

        if not cypher or not cypher.strip():
            self.errors.append("Empty Cypher query")
            return False, self.errors, self.warnings

        # Check for common syntax errors
        for pattern, message in self.SYNTAX_ERROR_PATTERNS:
            if re.search(pattern, cypher, re.IGNORECASE):
                self.errors.append(f"Syntax error: {message}")

        # Check for balanced parentheses and brackets
        if not self._check_balanced(cypher, '(', ')'):
            self.errors.append("Unbalanced parentheses")
        if not self._check_balanced(cypher, '[', ']'):
            self.errors.append("Unbalanced brackets")
        if not self._check_balanced(cypher, '{', '}'):
            self.errors.append("Unbalanced braces")

        # Check for valid node types
        node_types = self._extract_node_types(cypher)
        for node_type in node_types:
            if node_type not in self.VALID_NODE_TYPES:
                self.warnings.append(f"Unknown node type: {node_type}")

        # Check for valid relationships
        relationships = self._extract_relationships(cypher)
        for rel in relationships:
            if rel and rel not in self.VALID_RELATIONSHIPS:
                self.warnings.append(f"Unknown relationship: {rel}")

        # Check for process_id parameter
        if '$process_id' not in cypher and 'process_id' not in cypher:
            self.warnings.append("Missing process_id filter - query may return data from all documents")

        is_valid = len(self.errors) == 0
        return is_valid, self.errors, self.warnings

    def _check_balanced(self, text: str, open_char: str, close_char: str) -> bool:
        """Check if characters are balanced."""
        count = 0
        for char in text:
            if char == open_char:
                count += 1
            elif char == close_char:
                count -= 1
            if count < 0:
                return False
        return count == 0

    def _extract_node_types(self, cypher: str) -> List[str]:
        """Extract node type labels from Cypher."""
        # Pattern: (:Label) or (var:Label) or (var:Label {props})
        pattern = r'\(\s*\w*\s*:\s*(\w+)'
        matches = re.findall(pattern, cypher)
        return list(set(matches))

    def _extract_relationships(self, cypher: str) -> List[str]:
        """Extract relationship types from Cypher."""
        # Pattern: -[:REL_TYPE]-> or -[var:REL_TYPE]->
        pattern = r'-\s*\[\s*\w*\s*:\s*(\w+)\s*\]->'
        matches = re.findall(pattern, cypher)
        return list(set(matches))


