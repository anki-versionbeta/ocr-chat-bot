def test_structural_probe(process_id: str, search_terms: List[str]) -> Dict[str, Any]:
    """
    Test the structural probe functionality.

    Args:
        process_id: Document UUID
        search_terms: List of terms to search for

    Returns:
        Dict with probe results and analysis
    """
    logger.info(f"Testing structural probe for process_id: {process_id}")
    logger.info(f"Search terms: {search_terms}")

    neo4j_tools = Neo4jTools()

    try:
        probe_result = neo4j_tools.structural_probe(process_id, search_terms)

        analysis = {
            "probe_result": probe_result,
            "node_counts": probe_result.get("node_counts", {}),
            "terms_found": list(probe_result.get("found_in", {}).keys()),
            "recommended_paths": probe_result.get("recommended_paths", []),
            "data_locations": probe_result.get("data_locations", []),
            "issues": []
        }

        # Check if probe found anything
        if not probe_result.get("found_in"):
            analysis["issues"].append("Structural probe found no matching data")

        # Check node counts
        node_counts = probe_result.get("node_counts", {})
        if node_counts.get("cells", 0) == 0 and node_counts.get("lines", 0) == 0:
            analysis["issues"].append("Document has no Cell or Line nodes")

        return analysis

    finally:
        neo4j_tools.close()


